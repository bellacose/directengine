/**
 * Host routing so /go/{program}/ and /track/ on each site's own domain reach the Supabase Edge
 * Functions `go` and `track` (T8), and the public forms' POSTs to /submit-claim/ and /report-change/
 * reach `submit-claim` and `report-change` (T11), and the claim confirmation link /confirm-claim/?token=
 * reaches `confirm-claim` (T19). The build writes these files into the output folder:
 *
 *   _redirects     Netlify: proxy (200) rules. Cloudflare Pages can't proxy to another domain this way.
 *   _worker.js     Cloudflare Pages (advanced mode): forwards those paths, serves everything
 *   _routes.json   else as static files; _routes.json keeps the worker off all other paths.
 *
 * Both hosts' files are written unless the build runs on one of them (NETLIFY or CF_PAGES set), in
 * which case only that host's files are. The site slug is baked in: the host, not the page, tells
 * the function which site a click belongs to. The functions URL is public; no key is involved.
 */

import { writeFileSync } from "node:fs";
import { join } from "node:path";

type Env = Record<string, string | undefined>;

/** Reserved host for builds without SUPABASE_URL (fixture builds): can never resolve. */
export const PREVIEW_FUNCTIONS = "https://functions.preview.invalid/functions/v1";

/** `${SUPABASE_URL}/functions/v1`, or the preview placeholder when SUPABASE_URL isn't set. */
export function functionsBase(env: Env): string {
  const url = env.SUPABASE_URL?.trim();
  if (!url) return PREVIEW_FUNCTIONS;
  return `${new URL(url).origin}/functions/v1`;
}

export function netlifyRedirects(site: string, base: string): string {
  return [
    "# Generated by the build (apps/web/src/lib/host-routing.ts). Affiliate redirects and click",
    "# tracking go to Supabase Edge Functions; the site slug tells them which site this is.",
    `/go/*     ${base}/go/${site}/:splat     200!`,
    `/track/*  ${base}/track/${site}/:splat  200!`,
    `/submit-claim/*   ${base}/submit-claim/${site}/:splat   200!`,
    `/report-change/*  ${base}/report-change/${site}/:splat  200!`,
    `/confirm-claim/*  ${base}/confirm-claim/${site}/:splat  200!`,
    "",
  ].join("\n");
}

export function cloudflareWorker(site: string, base: string): string {
  return `// Generated by the build (apps/web/src/lib/host-routing.ts). Cloudflare Pages advanced mode.
// /go/*, /track/*, /submit-claim/*, /report-change/* and /confirm-claim/* go to Supabase Edge Functions with this
// site's slug; all else is static. Only /confirm-claim/ keeps its query string (the emailed token).
const BASE = ${JSON.stringify(base)};
const SITE = ${JSON.stringify(site)};
const FORWARD = ["user-agent", "referer", "content-type", "accept", "cf-connecting-ip"];

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const m = url.pathname.match(/^\\/(go|track|submit-claim|report-change|confirm-claim)\\/(.*)$/);
    if (!m) return env.ASSETS.fetch(request);
    const headers = new Headers();
    for (const h of FORWARD) {
      const v = request.headers.get(h);
      if (v) headers.set(h, v);
    }
    const hasBody = request.method !== "GET" && request.method !== "HEAD";
    const query = m[1] === "confirm-claim" ? url.search : "";
    return fetch(BASE + "/" + m[1] + "/" + SITE + "/" + m[2] + query, {
      method: request.method,
      headers,
      body: hasBody ? request.body : undefined,
      redirect: "manual",
    });
  },
};
`;
}

export const CLOUDFLARE_ROUTES = JSON.stringify({ version: 1, include: ["/go/*", "/track/*", "/submit-claim/*", "/report-change/*", "/confirm-claim/*"], exclude: [] }, null, 2) + "\n";

/** File name to contents, for this build's host (or both hosts when built elsewhere). */
export function hostRoutingFiles(site: string, env: Env): Record<string, string> {
  const base = functionsBase(env);
  const files: Record<string, string> = {};
  if (!env.CF_PAGES) files["_redirects"] = netlifyRedirects(site, base);
  if (!env.NETLIFY) {
    files["_worker.js"] = cloudflareWorker(site, base);
    files["_routes.json"] = CLOUDFLARE_ROUTES;
  }
  return files;
}

/** Called from astro.config.mjs after a build. */
export function writeHostRouting(outDir: string, env: Env): void {
  const site = env.SITE?.trim();
  if (!site || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(site)) throw new Error(`SITE is not a site slug: ${site}`);
  if (!env.SUPABASE_URL) console.warn(`[host-routing] SUPABASE_URL not set; /go/ and /track/ point at ${PREVIEW_FUNCTIONS}`);
  for (const [name, body] of Object.entries(hostRoutingFiles(site, env))) writeFileSync(join(outDir, name), body);
}
